import assert from 'node:assert/strict';
import { classifyIntegrated3DS as parse, mayContinue3DS as allowed } from './lib/worldpay/three-ds-flow.mjs';
const base='https://try.access.worldpay.com/api/payments/abc';
const ddc={outcome:'3dsDeviceDataRequired',deviceDataCollection:{jwt:'jwt',url:'https://example.com/ddc'},_actions:{supply3dsDeviceData:{href:base+'/3dsDeviceData',method:'POST'}}};
const challenge={outcome:'3dsChallenged',challenge:{jwt:'jwt',reference:'ref',url:'https://example.com/challenge'},_actions:{complete3dsChallenge:{href:base+'/3dsChallenges',method:'POST'}}};
assert.equal(parse(ddc,202).step,'device_data');
assert.equal(parse(challenge,202).step,'challenge');
assert.equal(parse({...ddc,_actions:{supply3dsDeviceData:{href:'https://evil.example/api/payments/abc',method:'POST'}}},202).step,'unknown');
assert.equal(parse({...ddc,_actions:{supply3dsDeviceData:{href:base+'/3dsDeviceData',method:'GET'}}},202).step,'unknown');
assert.equal(parse({...challenge,challenge:{...challenge.challenge,jwt:undefined}},202).step,'unknown');
assert.equal(parse({outcome:'authorized'},201).step,'authorised');
assert.equal(parse({outcome:'authorized'},500).step,'unknown');
assert.equal(parse({outcome:'sentForSettlement'},201).step,'settlement_requested');
assert.equal(parse({outcome:'someNewSuccess'},201).step,'unknown');
assert.equal(allowed('device_data','supply3dsDeviceData'),true);
assert.equal(allowed('challenge','complete3dsChallenge'),true);
assert.equal(allowed('authorised','complete3dsChallenge'),false);
assert.equal(allowed('challenge','supply3dsDeviceData'),false);
console.log('13 3DS state transition assertions passed');
