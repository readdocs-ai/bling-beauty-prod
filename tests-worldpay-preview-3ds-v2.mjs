import assert from 'node:assert/strict';
import { buildTryPaymentPayload } from './lib/worldpay/preview-payment-payload.mjs';
import { parseDeviceData } from './lib/worldpay/device-data.mjs';
import { canFinalisePaid } from './lib/worldpay/transaction-coordinator.mjs';
const reference='BLING-11111111-2222-4333-8444-555555555555';
const order={reference,status:'payment_processing',amount_pence:13000,currency:'GBP'};
const session='https://try.access.worldpay.com/sessions/session-123';
const browser={returnUrl:'https://bling-preview-123.vercel.app/api/worldpay/preview-challenge-return',userAgent:'Mozilla/5.0 test',language:'en-GB',width:1920,height:1080,timeZone:0};
const payload=buildTryPaymentPayload(order,session,'default','BLING BEAUTY',browser);
assert.equal(payload.instruction.threeDS.type,'integrated');
assert.equal(payload.instruction.threeDS.challenge.returnUrl,browser.returnUrl);
assert.equal(payload.instruction.value.amount,13000);
assert.equal(payload.instruction.paymentInstrument.sessionHref,session);
assert.equal(payload.instruction.threeDS.deviceData.channel,'browser');
assert.throws(()=>buildTryPaymentPayload(order,session,'default','BLING BEAUTY',{...browser,returnUrl:'https://attacker.example/api/worldpay/preview-challenge-return'}));
assert.throws(()=>buildTryPaymentPayload(order,session,'default','BLING BEAUTY',{...browser,width:0}));
assert.throws(()=>buildTryPaymentPayload({...order,status:'pending'},session,'default','BLING BEAUTY',browser));
assert.throws(()=>buildTryPaymentPayload(order,'https://access.worldpay.com/sessions/abc','default','BLING BEAUTY',browser));
const ddc={url:'https://centinelapistag.cardinalcommerce.com/V1/Cruise/Collect',jwt:'abcdefghijklmnopqrstuvwxyz.ABCDEFGHIJKLMN.123456789000000000',bin:'400000'};
assert.equal(parseDeviceData(ddc)?.bin,'400000');
assert.equal(parseDeviceData({...ddc,bin:'not-a-bin'}),null);
assert.equal(parseDeviceData({...ddc,url:'http://127.0.0.1/'}),null);
assert.equal(canFinalisePaid({stage:'settlement_requested',providerQuery:{transactionReference:reference,amount:13000,currency:'GBP',lastEvent:'sentForSettlement'},expectedReference:reference,expectedAmount:13000}),false);
assert.equal(canFinalisePaid({stage:'settlement_requested',providerQuery:{transactionReference:reference,amount:13000,currency:'GBP',lastEvent:'settled'},expectedReference:reference,expectedAmount:13000}),true);
console.log('PASS: 14 Preview Integrated 3DS payload, browser and settlement guards; no provider calls');
