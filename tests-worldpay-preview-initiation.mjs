import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildTryPaymentPayload } from './lib/worldpay/preview-payment-payload.mjs';
const o={reference:'BLING-aaaaaaaa-aaaa-4aaa-aaaa-aaaaaaaaaaaa',status:'payment_processing',currency:'GBP',amount_pence:1299};
const s='https://try.access.worldpay.com/sessions/abc-xyz';
const p=buildTryPaymentPayload(o,s,'default','Bling Beauty');
assert.equal(p.instruction.value.amount,1299);
assert.equal(p.instruction.paymentInstrument.type,'checkout');
assert.equal(p.transactionReference,o.reference);
for(const v of ['https://evil.example/sessions/abc','http://try.access.worldpay.com/sessions/abc','https://try.access.worldpay.com/sessions/abc?x=1'])
  assert.throws(()=>buildTryPaymentPayload(o,v,'default','Bling Beauty'));
assert.throws(()=>buildTryPaymentPayload({...o,amount_pence:1,status:'pending'},s,'default','Bling Beauty'));
assert.throws(()=>buildTryPaymentPayload({...o,currency:'USD'},s,'default','Bling Beauty'));
assert.throws(()=>buildTryPaymentPayload({...o,amount_pence:0},s,'default','Bling Beauty'));
const route=readFileSync('app/api/worldpay/preview-initiate/route.ts','utf8');
assert.match(route,/BLING_PREVIEW_PAYMENT_INITIATION/);
assert.match(route,/BLING_PREVIEW_PAYMENT_OWNERSHIP_VERIFIED/);
assert.match(route,/await createIntegratedPayment\(/);
assert.match(route,/claimOwnedPreviewAttempt/);
assert.match(route,/storeVerifiedProviderProgress/);
console.log('PASS 10 payload and fail-closed route checks');
const checkout=readFileSync('app/api/checkout/route.ts','utf8');
const ownership=readFileSync('lib/worldpay/preview-ownership.ts','utf8');
const migration=readFileSync('supabase/worldpay-preview-attempt-ownership-v4.sql','utf8');
assert.match(checkout,/randomBytes\(32\)/);
assert.match(checkout,/browser_secret_sha256: ownershipHash/);
assert.match(ownership,/bling_claim_owned_payment/);
assert.match(migration,/browser_secret_sha256=p_secret_sha256/);
assert.match(migration,/status='pending' AND payment_claim_id IS NULL/);
console.log('PASS 5 ownership and atomic-claim checks');
