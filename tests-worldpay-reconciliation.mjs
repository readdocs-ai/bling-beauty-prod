import assert from 'node:assert/strict';
import {classifyPaymentQuery,canRecordSettledEvidence} from './lib/worldpay/reconciliation-policy.mjs';
const ref='BLING-123e4567-e89b-42d3-a456-426614174000';
const expected={reference:ref,amountPence:13000,entity:'default'};
const sample=(lastEvent='authorizationSucceeded',extra={})=>({_embedded:{payments:[{transactionReference:ref,paymentId:'pay_test_123',entity:'default',value:{currency:'GBP',amount:13000},lastEvent,...extra}]}});
let count=0;
const check=(name,body,state,reason)=>{const x=classifyPaymentQuery(body,expected);assert.equal(x.state,state,name);if(reason)assert.equal(x.reason,reason);count++};
check('empty',{_embedded:{payments:[]}},'pending','not_indexed_yet');
check('declined',sample('authorizationRefused'),'failed');
check('failed',sample('authorizationFailed'),'failed');
check('authorised',sample('authorizationSucceeded'),'pending');
check('settlement requested',sample('settlementRequestSubmitted'),'pending');
check('settled summary not proof',sample('settled'),'pending');
check('unknown',sample('unknown-new-event'),'uncertain');
check('bad amount',sample('authorizationSucceeded',{value:{currency:'GBP',amount:1}}),'uncertain');
check('bad entity',sample('authorizationSucceeded',{entity:'other'}),'uncertain');
check('bad currency',sample('authorizationSucceeded',{value:{currency:'USD',amount:13000}}),'uncertain');
check('bad reference',sample('authorizationSucceeded',{transactionReference:'other'}),'uncertain');
check('bad payment ID',sample('authorizationSucceeded',{paymentId:'!'}),'uncertain');
check('duplicate',{_embedded:{payments:[sample()._embedded.payments[0],sample()._embedded.payments[0]]}},'uncertain');
check('malformed',{},'uncertain');
const result=classifyPaymentQuery(sample('settled'),expected);
assert.equal(canRecordSettledEvidence(result,{paymentId:'pay_test_123',settlementEvent:'settled',independentlyVerified:false}),false);count++;
assert.equal(canRecordSettledEvidence(result,{paymentId:'other',settlementEvent:'settled',independentlyVerified:true}),false);count++;
assert.equal(canRecordSettledEvidence(result,{paymentId:'pay_test_123',settlementEvent:'settled',independentlyVerified:true}),true);count++;
console.log(`PASS: ${count} reconciliation and settlement safety checks; no Worldpay calls`);
