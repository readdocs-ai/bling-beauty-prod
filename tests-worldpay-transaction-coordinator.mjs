import assert from 'node:assert/strict';
import { TRANSACTION_STAGES as S,validateServerOrder,claimRequired,classifyProviderResponse,permittedContinuation,canFinalisePaid } from './lib/worldpay/transaction-coordinator.mjs';
const ref='BLING-123e4567-e89b-12d3-a456-426614174000';
const o={reference:ref,status:'pending',currency:'GBP',amount_pence:1200,payment_claim_id:null};
assert.equal(validateServerOrder(o).amount,1200);
assert.equal(claimRequired(o),true);
assert.throws(()=>claimRequired({...o,payment_claim_id:'claimed'}));
assert.throws(()=>validateServerOrder({...o,amount_pence:1.2}));
assert.equal(classifyProviderResponse({status:201,data:{outcome:'authorized'}},S.PROCESSING).stage,S.AUTHORISED);
assert.equal(classifyProviderResponse({status:201,data:{outcome:'sentForSettlement'}},S.AUTHORISED).stage,S.SETTLEMENT);
assert.equal(classifyProviderResponse({status:500,data:{outcome:'sentForSettlement'}},S.AUTHORISED).stage,S.UNCERTAIN);
assert.equal(classifyProviderResponse({status:201,data:{outcome:'authorized'}},S.PAID).stage,S.UNCERTAIN);
assert.equal(permittedContinuation(S.AUTHORISED,'complete3dsChallenge'),false);
assert.equal(permittedContinuation(S.DEVICE,'supply3dsDeviceData'),true);
assert.equal(permittedContinuation(S.CHALLENGE,'complete3dsChallenge'),true);
const q={transactionReference:ref,amount:1200,currency:'GBP',lastEvent:'settled'};
assert.equal(canFinalisePaid({stage:S.SETTLEMENT,providerQuery:q,expectedReference:ref,expectedAmount:1200}),true);
assert.equal(canFinalisePaid({stage:S.SETTLEMENT,providerQuery:{...q,lastEvent:'sentForSettlement'},expectedReference:ref,expectedAmount:1200}),false);
assert.equal(canFinalisePaid({stage:S.AUTHORISED,providerQuery:q,expectedReference:ref,expectedAmount:1200}),false);
assert.equal(canFinalisePaid({stage:S.SETTLEMENT,providerQuery:{...q,amount:1300},expectedReference:ref,expectedAmount:1200}),false);
assert.equal(canFinalisePaid({stage:S.SETTLEMENT,providerQuery:{...q,lastEvent:'authorized'},expectedReference:ref,expectedAmount:1200}),false);
console.log('15 coordinator assertions passed');
